export function isLabCatalogKey(key: string): key is LabCatalogKey {
  return Object.hasOwn(LAB_CATALOG_EN, key);
}

export function labCatalogKeys(): LabCatalogKey[] {
  return (Object.keys(LAB_CATALOG_EN) as LabCatalogKey[]).sort();
}

export function labCatalogText(locale: Locale, key: LabCatalogKey): string {
  return closedText(locale, key, LAB_CATALOG_EN, LAB_CATALOG_OVERRIDES);
}

export function labSupplement(locale: Locale, key: LabSupplementKey, vars?: MessageVars): string {
  return interpolate(closedText(locale, key, LAB_SUPPLEMENT_EN, LAB_SUPPLEMENT_OVERRIDES), vars);
}
